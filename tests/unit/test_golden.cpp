// A committed project, read back byte for byte.
//
// The plan asks for forward-only migrations with golden fixtures. This is the fixture half: a
// real project directory, checked in, that this build must still open and must still write
// identically. A change to the writer therefore shows up as a failing test with a diff, and the
// person making it has to decide -- deliberately -- whether it is a compatible change or one that
// needs a schema version and a migration. Without it, the format drifts one harmless-looking
// commit at a time and the first person to notice is someone whose project will not open.
//
// The fixture is generated by this test if it is missing, which keeps it from rotting into
// something nobody can regenerate. Creating it fails the run: a golden file that was written by
// the same run that checked it has proved nothing.

